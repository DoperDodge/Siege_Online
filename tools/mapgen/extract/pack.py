"""Pack the extraction outputs into data/maps/oregon/extracted.json: derived numbers only (wall boxes, openings,
overlay vectors, icon points, cross-floor fits, accuracy). Never an image or image bytes.

usage: python3 -I pack.py <out dir> <points.json> <oregon.svg> <blueprint zip> <extracted.json>
The svg and the zip are only hashed, so the file records which downloads it came from.
"""
import hashlib
import json
import sys

FLOORS = {'0': 'B', '1': '1F', '2': '2F', '3': '3F', '4': 'RF'}


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def line_json(value, indent=''):
    """JSON with one record per line inside every list of objects, so diffs stay readable."""
    if isinstance(value, dict):
        if not value:
            return '{}'
        inner = indent + ' '
        parts = [f'{inner}{json.dumps(k)}: {line_json(v, inner)}' for k, v in value.items()]
        return '{\n' + ',\n'.join(parts) + '\n' + indent + '}'
    if isinstance(value, list) and value and all(isinstance(v, dict) for v in value):
        inner = indent + ' '
        return '[\n' + ',\n'.join(inner + json.dumps(v, ensure_ascii=False) for v in value) + '\n' + indent + ']'
    return json.dumps(value, ensure_ascii=False)


def main():
    out_dir, points_path, svg_path, zip_path, dest = sys.argv[1:6]
    combined = json.load(open(f'{out_dir}/walls_oregon.json'))
    vectors = json.load(open(f'{out_dir}/svg_vectors.json'))
    points = json.load(open(points_path))
    floors = {}
    for name, f in combined['floors'].items():
        floors[name] = dict(walls=f['walls'], openings=f['openings'])
    vec = {}
    for num, f in sorted(vectors.items()):
        layers = {k: v for k, v in sorted(f.get('layers', {}).items())}
        if layers:
            vec[FLOORS[num]] = layers
    pts = []
    for p in points:
        layer = p['layer']
        floor, kind = layer.split('-', 1)
        pts.append(dict(floor=FLOORS.get(floor, 'EXT' if floor == 'bg' else floor), kind=kind, id=p['id'],
                        tag=p['tag'], txt=p['txt'], rect=[p['x0'], p['y0'], p['x1'], p['y1']], c=[p['cx'], p['cy']]))
    pts.sort(key=lambda p: (p['floor'], p['kind'], p['c'][0], p['c'][1], p['id']))
    doc = (
        'Generated by tools/mapgen/extract (see its README); do not edit. Derived numbers only, read from the '
        'r6calls Oregon SVG (floor rasters, overlay vectors, icons) and checked against the official blueprint: '
        'no image data. Units: u (research/oregon/layout_notes.md §1) in each floor image\'s own frame (2F is '
        'about 2.4% larger than 1F; cross_floor has the fits). walls[].rect / openings[].rect = [x0, y0, x1, y1]; '
        'k = H (runs along x) or V (along y); c = centre line; t = drawn thickness. The authoring files '
        'data/maps/oregon/walls_<floor>.json were seeded from this file; the drift test compares them.'
    )
    packed = dict(
        _doc=doc,
        sources=dict(
            svg=dict(url='https://r6calls.com/img/maps/oregon.svg', sha256=sha256(svg_path)),
            blueprint=dict(url='https://ubistatic-a.ubisoft.com/0106/gamesites/rainbow6/blueprints/r6-maps-oregon-blueprints.zip',
                           sha256=sha256(zip_path)),
        ),
        cross_floor=combined['cross_floor'],
        accuracy=combined['accuracy'],
        floors=floors,
        vectors=vec,
        points=pts,
    )
    with open(dest, 'w', encoding='utf-8') as f:
        f.write(line_json(packed) + '\n')
    print(f'wrote {dest}: ' + ', '.join(f'{k} {len(v["walls"])} walls / {len(v["openings"])} openings' for k, v in floors.items())
          + f', {len(pts)} points')


if __name__ == '__main__':
    main()
